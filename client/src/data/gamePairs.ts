/** Unique hanzi → pinyin (first wins on duplicates like 月) */
export function uniqueWordPairs(): WordPair[] {
  const seen = new Set<string>();
  const out: WordPair[] = [];
  for (const p of WORD_PAIRS) {
    if (seen.has(p.hanzi)) continue;
    seen.add(p.hanzi);
    out.push(p);
  }
  return out;
}
